#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..")

// Additional destinations let a host repository keep its bundled backend
// contract current without copying this generator or the manifest.
export async function generateContract({ check = false, javascriptOutputs = [] } = {}) {
  const manifest = JSON.parse(await readFile(resolve(packageRoot, "Contract/auriui-v1.json"), "utf8"))
  validate(manifest)

  const javascript = renderJavaScript(manifest)
  const outputs = new Map([
    [resolve(packageRoot, "Sources/AuriUI/AuriUIContract.generated.swift"), renderSwift(manifest)],
    [resolve(packageRoot, "Contract/auriui-v1.generated.mjs"), javascript],
    ...javascriptOutputs.map((path) => [path, javascript]),
  ])

  if (check) {
    const stale = []
    for (const [path, expected] of outputs) {
      const actual = await readFile(path, "utf8").catch(() => null)
      if (actual !== expected) stale.push(path)
    }
    if (stale.length > 0) {
      console.error("AuriUI contract output is stale. Run the contract generator without --check.")
      for (const path of stale) console.error(`- ${path}`)
      process.exitCode = 1
    } else {
      console.log("AuriUI contract output is current.")
    }
  } else {
    for (const [path, contents] of outputs) {
      await writeFile(path, contents)
    }
    console.log("Generated the AuriUI Swift and JavaScript contracts.")
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await generateContract({ check: process.argv.includes("--check") })
}

function validate(value) {
  if (value?.schemaVersion !== 1 || value?.protocol?.version !== 1) {
    throw new Error("Only the AuriUI v1 contract schema is supported")
  }

  const roles = ["leaf", "container", "structural", "item"]
  const knownKeywords = new Set()
  for (const role of roles) {
    const keywords = value.keywords?.[role]
    if (!Array.isArray(keywords) || keywords.length === 0) {
      throw new Error(`keywords.${role} must be a non-empty array`)
    }
    for (const keyword of keywords) {
      if (!isIdentifier(keyword) || knownKeywords.has(keyword)) {
        throw new Error(`Invalid or duplicate keyword: ${keyword}`)
      }
      knownKeywords.add(keyword)
    }
  }

  if (!Array.isArray(value.grammarRules) || value.grammarRules.length === 0) {
    throw new Error("grammarRules must be a non-empty array")
  }
  if (!Array.isArray(value.components) || value.components.length === 0) {
    throw new Error("components must be a non-empty array")
  }

  const componentIDs = new Set()
  for (const component of value.components) {
    if (!isIdentifier(component.id) || componentIDs.has(component.id)) {
      throw new Error(`Invalid or duplicate component id: ${component.id}`)
    }
    componentIDs.add(component.id)
    if (!knownKeywords.has(component.rootKeyword)) {
      throw new Error(`${component.id} has unknown root keyword ${component.rootKeyword}`)
    }
    if (!Array.isArray(component.keywords) || component.keywords.length === 0) {
      throw new Error(`${component.id} must declare its keywords`)
    }
    for (const keyword of component.keywords) {
      if (!knownKeywords.has(keyword)) {
        throw new Error(`${component.id} references unknown keyword ${keyword}`)
      }
    }
    if (!component.prompt || !component.sample) {
      throw new Error(`${component.id} must declare prompt and sample text`)
    }
    if (component.requiresClientSupport && (!component.supportedPrompt || !component.unsupportedPrompt)) {
      throw new Error(`${component.id} must declare both compatibility prompts`)
    }
  }
}

function isIdentifier(value) {
  return typeof value === "string" && /^[a-z][a-z0-9]*$/.test(value)
}

function renderJavaScript(value) {
  const grammar = [
    "## Rules",
    ...value.grammarRules.map((rule) => `- ${rule}`),
    "- Components:",
    ...value.components.map((component) => `  - ${component.prompt}`),
  ].join("\n")
  const components = value.components.map((component) => ({
    id: component.id,
    keywords: component.keywords,
    sample: component.sample,
    requiresClientSupport: component.requiresClientSupport === true,
  }))
  const clientComponents = value.components
    .filter((component) => component.requiresClientSupport)
    .map((component) => ({
      id: component.id,
      keywords: component.keywords,
      supportedPrompt: component.supportedPrompt,
      unsupportedPrompt: component.unsupportedPrompt,
    }))

  return `// Generated by AuriUI/Scripts/generate-contract.mjs from
// AuriUI/Contract/auriui-v1.json. Do not edit by hand.

export const AUI_CONTRACT_VERSION = ${value.protocol.version}

export const AUI_GRAMMAR_INSTRUCTIONS = ${JSON.stringify(grammar)}

export const AUI_COMPONENTS = Object.freeze(${JSON.stringify(components, null, 2)})

export const AUI_CLIENT_COMPONENTS = Object.freeze(${JSON.stringify(clientComponents, null, 2)})

export const AUI_LEAF_KEYWORDS = Object.freeze(${JSON.stringify(value.keywords.leaf)})
export const AUI_CONTAINER_KEYWORDS = Object.freeze(${JSON.stringify(value.keywords.container)})
export const AUI_STRUCTURAL_KEYWORDS = Object.freeze(${JSON.stringify(value.keywords.structural)})
export const AUI_ITEM_KEYWORDS = Object.freeze(${JSON.stringify(value.keywords.item)})
`
}

function renderSwift(value) {
  const components = value.components.map((component) => `        Component(
            id: ${swiftString(component.id)},
            keywords: ${swiftArray(component.keywords)},
            sample: ${swiftString(component.sample)},
            requiresClientSupport: ${component.requiresClientSupport === true}
        )`).join(",\n")
  const componentCases = value.components.map((component) => `        case .${component.id}:
            return ${swiftString(component.id)}`).join("\n")
  const advertised = value.components
    .filter((component) => component.requiresClientSupport)
    .map((component) => component.id)

  return `// Generated by AuriUI/Scripts/generate-contract.mjs from
// AuriUI/Contract/auriui-v1.json. Do not edit by hand.

public enum AuriUIContract {
    public static let version = ${value.protocol.version}

    struct Component: Equatable, Sendable {
        let id: String
        let keywords: [String]
        let sample: String
        let requiresClientSupport: Bool

        init(id: String, keywords: [String], sample: String, requiresClientSupport: Bool) {
            self.id = id
            self.keywords = keywords
            self.sample = sample
            self.requiresClientSupport = requiresClientSupport
        }
    }

    static let components: [Component] = [
${components}
    ]

    public static let componentIDs: [String] = ${swiftArray(value.components.map((component) => component.id))}
    public static let advertisedComponentIDs: [String] = ${swiftArray(advertised)}

    static let leafKeywords: Set<String> = ${swiftSet(value.keywords.leaf)}
    static let containerKeywords: Set<String> = ${swiftSet(value.keywords.container)}
    static let structuralKeywords: Set<String> = ${swiftSet(value.keywords.structural)}
    static let itemKeywords: Set<String> = ${swiftSet(value.keywords.item)}
    static let knownKeywords = leafKeywords
        .union(containerKeywords)
        .union(structuralKeywords)
        .union(itemKeywords)
}

extension AuriUISection {
    var contractComponentID: String {
        switch self {
${componentCases}
        }
    }
}
`
}

function swiftArray(values) {
  return `[${values.map(swiftString).join(", ")}]`
}

function swiftSet(values) {
  return `Set(${swiftArray(values)})`
}

function swiftString(value) {
  return JSON.stringify(value)
}
